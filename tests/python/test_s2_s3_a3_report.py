"""Checks tools/s2_s3/a3_report.py on small hand-written CSVs."""
import csv

import pytest

from tools.s2_s3 import a3_report as rep

MODES = ("view", "max", "realloc")


def row(image="input1_000001", scale="0.5", k=500, mode="view", repeat=0, warmup=False, count=500,
        selected=1000, s2=0.1, s3=0.05, host=0.3, alloc=0.0):
    times = {"s2_ms": s2, "s3_ms": s3, "t_fast": s2 / 4, "t_select": s2 / 4, "t_harris": s2 / 4,
             "t_rank": s2 / 4, "t_blur": s3 / 2, "t_describe": s3 / 2, "host_attempt_ms": host,
             "alloc_ms": alloc}
    out = {"case": f"{image}_s{scale}_k{k}", "image": image, "scale": scale, "width": "256", "height": "256",
           "k": str(k), "k_max": "4000", "mode": mode, "capacity": str(4000 if mode == "max" else k),
           "repeat": str(repeat), "is_warmup": str(int(warmup)), "count": str(count),
           "maxima_selected": str(selected), "s2_ws_bytes": "1000", "s3_ws_bytes": "2000",
           "kp_bytes": "300", "desc_bytes": "400", "gpu": "Tesla T4"}
    out.update({key: str(value) for key, value in times.items()})
    return out


def cell(repeats=3, **kwargs):
    """One warmup row (a large outlier) followed by `repeats` measured rows."""
    warm = row(warmup=True, repeat=0, **{**kwargs, "s2": 9.0})
    return [warm] + [row(repeat=r + 1, **kwargs) for r in range(repeats)]


def all_modes(**kwargs):
    rows = []
    for mode in MODES:
        rows += cell(mode=mode, **kwargs)
    return rows


def write_csv(path, rows, columns=None):
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=columns or list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return path


def test_quantile_interpolates_linearly():
    assert rep.quantile([4.0, 1.0, 3.0, 2.0], 0.95) == pytest.approx(3.85)
    assert rep.quantile([7.0], 0.95) == 7.0
    with pytest.raises(ValueError):
        rep.quantile([], 0.5)


def test_median_over_images_of_per_image_medians_and_saturation():
    rows = all_modes(image="a", s2=0.10) + all_modes(image="b", s2=0.30, count=420)
    rows += all_modes(image="c", s2=0.20)
    summary = rep.summarize(rows)
    s = summary[rep.Group("0.5", 500, "view")]
    assert s.images == 3 and s.repeats == 3
    assert s.median["s2_ms"] == pytest.approx(0.20)       # warmup outlier 9.0 dropped
    assert s.p95["s2_ms"] == pytest.approx(0.29)
    assert s.saturated == 1                               # image b kept 420 < K = 500
    assert s.count_median == 500


def test_missing_mode_is_rejected():
    rows = cell(mode="view") + cell(mode="max")
    with pytest.raises(ValueError, match="realloc"):
        rep.summarize(rows)


def test_uneven_repeats_are_rejected():
    rows = cell(mode="view", repeats=3) + cell(mode="max", repeats=2) + cell(mode="realloc", repeats=3)
    with pytest.raises(ValueError, match="repeats"):
        rep.summarize(rows)


def test_count_change_between_repeats_is_rejected():
    rows = all_modes()
    rows[1]["count"] = "499"
    with pytest.raises(ValueError, match="changes between repeats"):
        rep.summarize(rows)


def test_marks_overhead_compares_phase_sum_with_unmarked_total():
    summary = rep.summarize(all_modes())
    assert rep.marks_overhead(summary[rep.Group("0.5", 500, "view")]) == pytest.approx(0.0)


def test_latex_reports_deltas_against_view():
    rows = (cell(mode="view", s3=0.05, host=0.30) + cell(mode="max", s3=0.06, host=0.31)
            + cell(mode="realloc", s3=0.05, host=0.80, alloc=0.45))
    text = rep.render_latex(rep.summarize(rows))
    assert "0.5 & 500 & 500 & 0.100 & 0.050 & +0.010 & +0.500 \\\\" in text
    assert text.startswith("% Generated by tools/s2_s3/a3_report.py")


def test_latex_keeps_selected_scales_and_never_prints_negative_zero():
    rows = []
    for scale in ("0.25", "0.5", "1"):
        rows += (cell(scale=scale, mode="view", s3=0.0500) + cell(scale=scale, mode="max", s3=0.0499)
                 + cell(scale=scale, mode="realloc", s3=0.0500))
    text = rep.render_latex(rep.summarize(rows), scales=("0.5", "1"))
    body = [line for line in text.splitlines() if line.endswith("\\\\") and line[0].isdigit()]
    assert [line.split(" & ")[0] for line in body] == ["0.5", "1"]
    assert "-0.000" not in text and "+0.000" in text
    with pytest.raises(ValueError, match="0.75"):
        rep.render_latex(rep.summarize(rows), scales=("0.75",))


def test_jitter_summary_and_missing_mode():
    rows = [{"mode": m, "attempt": str(a), "k": "500", "host_attempt_ms": str(0.1 * (a + 1)),
             "alloc_ms": "0", "gpu": "Tesla T4"} for m in MODES for a in range(5)]
    j = rep.summarize_jitter(rows)
    assert j["view"]["attempts"] == 5 and j["view"]["p50"] == pytest.approx(0.3)
    with pytest.raises(ValueError, match="realloc"):
        rep.summarize_jitter([r for r in rows if r["mode"] != "realloc"])


def test_main_writes_outputs_and_rejects_missing_columns(tmp_path, capsys):
    path = write_csv(tmp_path / "a3.csv", all_modes())
    latex = tmp_path / "tables" / "a3.tex"
    markdown = tmp_path / "a3.md"
    assert rep.main([str(path), "--latex", str(latex), "--markdown", str(markdown)]) == 0
    assert latex.read_text().startswith("% Generated")
    assert "| 0.5 | 256×256 | 500 | view |" in markdown.read_text(encoding="utf-8")
    assert "Tesla T4" in capsys.readouterr().out

    rows = all_modes()
    columns = [c for c in rows[0] if c != "t_rank"]
    broken = write_csv(tmp_path / "broken.csv", [{c: r[c] for c in columns} for r in rows], columns)
    assert rep.main([str(broken)]) == 2
    assert "t_rank" in capsys.readouterr().err
